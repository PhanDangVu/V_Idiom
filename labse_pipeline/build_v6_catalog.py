def main():
    # 1. Copy 200_idioms-v5.csv và v-idiomV6.rdf vào labse_pipeline/data/
    shutil.copy2(CSV_V5_PATH, DATA_DIR / "200_idioms-v5.csv")
    shutil.copy2(OUTPUT_RDF_PATH, DATA_DIR / "v-idiomV6.rdf")
    print("✅ Đã chép 200_idioms-v5.csv và v-idiomV6.rdf vào labse_pipeline/data/")

    # 2. Sinh criteria_catalog.json cho 236 mã tiêu chí
    parsed = parse_criteria_from_markdown(MD_V5_PATH)
    catalog = {
        "Bối_cảnh": {},
        "Hành_động": {},
        "Kết_quả": {},
        "Mục_đích": {},
    }
    axis_map = {
        "BC": "Bối_cảnh",
        "HD": "Hành_động",
        "KQ": "Kết_quả",
        "MD": "Mục_đích",
    }

    for code, info in parsed.items():
        axis_key = axis_map[info["prefix"]]
        label_vi = code.split("_", 1)[1].replace("_", " ")
        label_en = EN_LABELS.get(code, label_vi)
        catalog[axis_key][code] = {
            "label_vi": label_vi,
            "desc_vi": info["desc_vi"],
            "label_en": label_en,
            "desc_en": f"{label_en} ({info['type']})",
            "type": info["type"],
            "examples": info["examples"],
        }

    out_path = DATA_DIR / "criteria_catalog.json"
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)

    print(
        f"✅ Đã cập nhật {out_path} với tổng cộng {sum(len(v) for v in catalog.values())} mã tiêu chí:"
    )
    for k, v in catalog.items():
        print(f"   - {k}: {len(v)} mã")


if __name__ == "__main__":
    main()
